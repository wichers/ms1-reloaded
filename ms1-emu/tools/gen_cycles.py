"""Generate src/cpu12_cycles.inc: HCS12 bus cycles per opcode and indexed form, taken from
Table A-1 (Instruction Set Summary) of the S12CPUV2 Reference Manual, Rev. 4.0.

The table's HCS12 "Access Detail" column lists one letter per bus cycle (P program word
fetch, r/R read, w/W write, O optional fetch, f free cycle, ...), so an instruction's cycle
count is the number of letters. Conditional branches list "taken/not taken".

Usage: pdftotext -layout S12CPUV2.pdf s12cpuv2.txt
       python3 -I tools/gen_cycles.py s12cpuv2.txt > src/cpu12_cycles.inc
"""
import re
import sys

TOK = r"(?:[0-9A-F]{2}|ii|dd|hh|ll|xb|ff|ee|rr|jj|kk|mm|pg|eb|lb|qq|tn|nn)(?=\s)"
MODE = r"(Special|INH|IMM|DIR|EXT|IDX|IDX1|IDX2|\[D,IDX\]|\[IDX2\]|REL|[A-Z0-9]+-[A-Z0-9]+)"
ROW = re.compile(r"\s" + MODE + r"\s+(" + TOK + r"(?: " + TOK + r")*)\s+(\S+)")
# Indexed forms, in the column order of the generated arrays.
CLASSES = {"IDX": 0, "IDX1": 1, "IDX2": 2, "[D,IDX]": 3, "[IDX2]": 4}


def count(detail):
    """Cycles of an access-detail string; footnote digits are not cycles."""
    return sum(ch.isalpha() for ch in detail)


def main():
    lines = open(sys.argv[1], encoding="utf-8").read().split("\n")
    start = next(i for i, l in enumerate(lines) if "Table A-1. Instruction Set Summary (Sheet 1 of" in l)
    end = next(i for i, l in enumerate(lines) if "Table A-2. CPU12 Opcode Map" in l)
    # [page][opcode] -> [5 classes], not-taken
    cyc = [[None] * 256 for _ in range(2)]
    nt = [[0] * 256 for _ in range(2)]
    for line in lines[start:end]:
        m = ROW.search(line)
        if not m:
            continue
        mode, code, detail = m[1], m[2].split(), m[3]
        page = 1 if code[0] == "18" else 0
        if page and code[1] == "tn":
            continue  # TRAP: handled as unimplemented opcode
        op = int(code[page], 16)
        if detail.startswith("("):  # STOP: "(entering STOP)"; cost of the instruction itself
            detail = "OOSSSSsf"
        taken, _, not_taken = re.sub(r"\d", "", detail).partition("/")
        row = cyc[page][op] or [None] * 5
        if mode in CLASSES:
            row[CLASSES[mode]] = count(taken)
        else:
            row = [count(taken)] * 5
        cyc[page][op] = row
        if not_taken:
            nt[page][op] = count(not_taken)
    print("/* Generated by tools/gen_cycles.py from S12CPUV2 Table A-1; do not edit. */")
    print("/* [opcode][form]: form 0 = non-indexed or IDX (5-bit, accumulator or auto inc/dec), */")
    print("/* 1 = IDX1 (9-bit), 2 = IDX2 (16-bit), 3 = [D,IDX], 4 = [IDX2]; 0 = unimplemented (TRAP). */")
    for page, name in ((0, "cpu12_cycles_p1"), (1, "cpu12_cycles_p2")):
        print(f"static const uint8_t {name}[256][5] = {{")
        for op in range(256):
            row = cyc[page][op]
            if row is None:
                row = [0] * 5
            elif row[0] is None:
                sys.exit(f"page {page + 1} opcode {op:02X}: no IDX form {row}")
            elif None in row:
                # forms the instruction does not support (bit instructions: no indirect; TBL/ETBL:
                # IDX only) cost as the longest form it lists
                row = [v if v is not None else max(x for x in row if x is not None) for v in row]
            print(f"\t[0x{op:02X}] = {{{', '.join(str(v) for v in row)}}},")
        print("};")
    for page, name in ((0, "cpu12_not_taken_p1"), (1, "cpu12_not_taken_p2")):
        print(f"/* conditional branches: cycles when not taken */")
        print(f"static const uint8_t {name}[256] = {{")
        for op in range(256):
            if nt[page][op]:
                print(f"\t[0x{op:02X}] = {nt[page][op]},")
        print("};")


main()

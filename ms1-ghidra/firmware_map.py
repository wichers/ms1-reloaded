"""Generate docs/firmware-map.md and docs/function-index.md from the Ghidra exports.

Inputs (paths relative to this file): out/facts.json and out/ms1_4011_decomp.c, written by
./ghidra.sh decompile, and the vector table in ida_export/ms1_firmware.bytes (the bootloader
and vectors are not in the BCI image).

Usage: python3 -I firmware_map.py
"""
import collections, json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
VECTOR_FILE_OFFSET = 0x7F80  # VECTORS (0xFF80) in ms1_firmware.bytes, per the IDA XML memory map
LARGE = 20000  # pseudocode characters above which a function is reported as large

# MC9S12D64 vector table, 0xFF80 + 2*n (device guide "Interrupt Vector Locations").
VECTORS = (["reserved"] * 6 + ["PWM emergency shutdown", "Port P"] + ["reserved"] * 16 +
           ["CAN0 transmit", "CAN0 receive", "CAN0 errors", "CAN0 wake-up", "FLASH", "EEPROM",
            "SPI2", "SPI1", "IIC", "BDLC", "CRG self-clock mode", "CRG PLL lock",
            "pulse accumulator B overflow", "modulus down counter underflow", "Port H", "Port J",
            "ATD1", "ATD0", "SCI1", "SCI0", "SPI0", "pulse accumulator A input edge",
            "pulse accumulator A overflow", "timer overflow"] +
           [f"timer channel {c}" for c in range(7, -1, -1)] +
           ["real-time interrupt", "IRQ", "XIRQ", "SWI", "unimplemented instruction trap",
            "COP failure reset", "clock monitor fail reset", "reset"])

# MC9S12D64 register block (INITRG = $00), by module.
MODULES = [
    (0x0000, 0x000F, "MEBI: ports A/B/E, mode"), (0x0010, 0x001F, "MMC: INITRM/INITRG/INITEE/MISC"),
    (0x0020, 0x002F, "DBG"), (0x0030, 0x0033, "MMC: PPAGE"), (0x0034, 0x003F, "CRG: clock, PLL, COP, RTI"),
    (0x0040, 0x007F, "ECT: timer"), (0x0080, 0x009F, "ATD0"), (0x00A0, 0x00C7, "PWM"),
    (0x00C8, 0x00CF, "SCI0"), (0x00D0, 0x00D7, "SCI1"), (0x00D8, 0x00DF, "SPI0"), (0x00E0, 0x00E7, "IIC"),
    (0x00E8, 0x00EF, "BDLC"), (0x00F0, 0x00F7, "SPI1"), (0x00F8, 0x00FF, "SPI2"),
    (0x0100, 0x010F, "FTS: flash control"), (0x0110, 0x011F, "EETS: EEPROM control"),
    (0x0120, 0x013F, "ATD1"), (0x0140, 0x017F, "MSCAN0"), (0x0180, 0x023F, "reserved / other MSCAN"),
    (0x0240, 0x027F, "PIM: ports T/S/M/P/H/J"), (0x0280, 0x03FF, "reserved"),
]
REGIONS = [(0x0800, 0x0BFF, "EEPROM"), (0x1000, 0x1FFF, "RAM")]


def module(addr):
    return next((m for lo, hi, m in MODULES if lo <= addr <= hi), "?")


def region(addr):
    return next((r for lo, hi, r in REGIONS if lo <= addr <= hi), None)


def decompile_status(path):
    status = {}
    text = open(path).read()
    for block in re.split(r"(?=/\* ===== )", text):
        m = re.match(r"/\* ===== (\S+) @ (\S+) ===== \*/", block)
        if not m:
            continue
        status[m[2]] = ("failed" if "decompile failed" in block else "large" if len(block) > LARGE
                        else "bad data" if "halt_baddata" in block else "ok")
    return status


def main():
    facts = json.load(open(os.path.join(HERE, "out", "facts.json")))
    labels = facts["labels_below_0x4000"]
    funcs = facts["functions"]
    by_name = {f["name"]: f for f in funcs}
    by_entry = {f["entry"]: f for f in funcs}
    status = decompile_status(os.path.join(HERE, "out", "ms1_4011_decomp.c"))
    callers = collections.defaultdict(set)
    for f in funcs:
        for c in f["calls"]:
            callers[c].add(f["name"])

    def reg_name(a):
        return labels.get(a, f"0x{a}")

    def modules_of(f):
        return sorted({module(int(a, 16)) for a in f["access"] if int(a, 16) < 0x400})

    raw = open(os.path.join(HERE, "ida_export", "ms1_firmware.bytes"), "rb").read()
    vec = [int.from_bytes(raw[VECTOR_FILE_OFFSET + 2 * n:VECTOR_FILE_OFFSET + 2 * n + 2], "big") for n in range(64)]

    def handler(target):
        t = by_entry.get(f"{target:x}")
        if t is None:
            return None, None
        if t.get("thunk_of"):
            return t, by_name.get(t["thunk_of"])
        if len(t["calls"]) == 1 and t["bytes"] <= 3:
            return t, by_name.get(t["calls"][0])
        return t, t

    m = []
    m.append("# MS1 firmware map — 4011 application image\n")
    m.append("Generated by `firmware_map.py` from `out/facts.json` and `out/ms1_4011_decomp.c` (both written by "
             "`./ghidra.sh decompile`) and the vector table in `ida_export/ms1_firmware.bytes`; regenerate after "
             "re-running the pipeline. Names are the firmware rebuild's where it has one (`./ghidra.sh names`), "
             "else the imported IDA names (hints) or Ghidra-generated; "
             "calls and register/memory accesses are read from the binary. Register accesses count loads and stores "
             "at constant addresses only — indexed accesses through a register are not resolved.\n")
    m.append("Per-function detail: [function-index.md](function-index.md).\n")

    m.append("## Memory map\n")
    m.append("| Range | Content | Set by |\n|---|---|---|")
    m.append("| `0x0000–0x03FF` | I/O registers | CRT init `INITRG = $00` |")
    m.append("| `0x0800–0x0BFF` | EEPROM (1 KB) | CRT init `INITEE = $09` |")
    m.append("| `0x1000–0x1FFF` | RAM (4 KB), stack top `0x2000` | CRT init `INITRM = $10`, `LDS #$2000` |")
    m.append("| `0x4000–0x7FFF` | flash page 3E (fixed) | hardware |")
    m.append("| `0x8000–0xBFFF` | `PPAGE` window — page 3D while the application runs | CRT init `PPAGE = $3D` |")
    m.append("| `0xC000–0xFFFF` | flash page 3F (fixed); bootloader from `0xF800`, vectors at `0xFF80` | hardware |")
    m.append("")

    m.append("## Interrupts\n")
    m.append("Vector `0xFF80 + 2·n` points at the trampoline `0xF740 + 3·n` (a one-`JMP` thunk); reset points at the "
             "bootloader (`0xF800`).\n")
    default = collections.Counter()
    rows = []
    for n, target in enumerate(vec):
        addr = 0xFF80 + 2 * n
        tramp, h = handler(target)
        hname = h["name"] if h else f"0x{target:04x}"
        if tramp is not None and h is not None:
            default[hname] += 1
        rows.append((addr, VECTORS[n], target, tramp, h, hname))
    common = default.most_common(1)[0][0] if default else None
    m.append("| Vector | Source | Trampoline | Handler | Bytes | Registers touched (modules) |\n|---|---|---|---|---|---|")
    for addr, src, target, tramp, h, hname in rows:
        if hname == common:
            continue
        mods = ", ".join(modules_of(h)) if h else ""
        m.append(f"| `0x{addr:04X}` | {src} | `0x{target:04X}` | `{hname}` | {h['bytes'] if h else ''} | {mods} |")
    if common:
        others = [src for addr, src, target, tramp, h, hname in rows if hname == common]
        m.append(f"\nThe other {len(others)} vectors reach `{common}` (`0x{by_name[common]['entry']}`), the shared "
                 f"default handler: {', '.join(sorted(set(others)))}.\n")

    m.append("## Peripherals\n")
    m.append("Functions that load (`r`) or store (`w`) each module's registers.\n")
    per_module = collections.defaultdict(lambda: collections.defaultdict(dict))
    for f in funcs:
        for a, rw in f["access"].items():
            addr = int(a, 16)
            if addr < 0x400:
                per_module[module(addr)][f["name"]][reg_name(a)] = rw
    for lo, hi, mod in MODULES:
        if mod not in per_module:
            continue
        users = per_module[mod]
        regs = sorted({r for d in users.values() for r in d})
        m.append(f"### {mod} (`0x{lo:04X}–0x{hi:04X}`)\n")
        m.append("Registers: " + ", ".join(f"`{r}`" for r in regs) + "\n")
        m.append("| Function | Accesses |\n|---|---|")
        for name in sorted(users, key=lambda n: by_name[n]["entry"]):
            acc = ", ".join(f"`{r}` {rw}" for r, rw in sorted(users[name].items()))
            m.append(f"| `{name}` | {acc} |")
        m.append("")

    m.append("## Shared state\n")
    m.append("RAM and EEPROM locations accessed by the most functions (constant-address accesses).\n")
    users = collections.defaultdict(lambda: {"r": set(), "w": set()})
    for f in funcs:
        for a, rw in f["access"].items():
            if region(int(a, 16)):
                for k in rw:
                    users[a][k].add(f["name"])
    top = sorted(users.items(), key=lambda kv: -len(kv[1]["r"] | kv[1]["w"]))[:40]
    m.append("| Address | Name | Region | Functions | Writers |\n|---|---|---|---|---|")
    for a, u in top:
        writers = sorted(u["w"])
        shown = ", ".join(f"`{w}`" for w in writers[:6]) + (f" … (+{len(writers) - 6})" if len(writers) > 6 else "")
        m.append(f"| `0x{a.upper()}` | `{reg_name(a)}` | {region(int(a, 16))} | {len(u['r'] | u['w'])} | {shown} |")
    m.append("")

    m.append("## Name groups\n")
    m.append("Functions grouped by the prefix of their imported name — a navigation aid; the names are hints.\n")
    groups = collections.defaultdict(list)
    for f in funcs:
        parts = f["name"].split("_")
        key = "_".join(parts[:2]) if parts[0] in ("p3d", "isr") and len(parts) > 1 else parts[0]
        groups[key].append(f)
    m.append("| Prefix | Functions | Bytes |\n|---|---|---|")
    for key, fs in sorted(groups.items(), key=lambda kv: -sum(f["bytes"] for f in kv[1])):
        m.append(f"| `{key}` | {len(fs)} | {sum(f['bytes'] for f in fs)} |")
    m.append("")

    idx = ["# Function index — 4011 application image\n",
           "Generated by `firmware_map.py`; see [firmware-map.md](firmware-map.md) for the sources and caveats. "
           "*Source* is the Ghidra symbol source (`USER_DEFINED` = the rebuild's or a verified name, `IMPORTED` = IDA name, `DEFAULT`/`ANALYSIS` = Ghidra). "
           "*Decompile* is the state of the function in `out/ms1_4011_decomp.c` "
           f"(`large` = more than {LARGE} characters of pseudocode).\n",
           "| Address | Function | Source | Bytes | Callers | Calls | Registers (modules) | Decompile |",
           "|---|---|---|---|---|---|---|---|"]
    for f in sorted(funcs, key=lambda f: (("::" in f["entry"]), f["entry"].rjust(16, "0"))):
        calls = ", ".join(f"`{c}`" for c in f["calls"])
        if f.get("thunk_of"):
            calls = f"thunk of `{f['thunk_of']}`"
        idx.append(f"| `{f['entry']}` | `{f['name']}` | {f['source']} | {f['bytes']} | {len(callers[f['name']])} | "
                   f"{calls} | {', '.join(modules_of(f))} | {status.get(f['entry'], '—')} |")

    os.makedirs(os.path.join(HERE, "docs"), exist_ok=True)
    open(os.path.join(HERE, "docs", "firmware-map.md"), "w").write("\n".join(m) + "\n")
    open(os.path.join(HERE, "docs", "function-index.md"), "w").write("\n".join(idx) + "\n")
    print(f"wrote docs/firmware-map.md and docs/function-index.md ({len(funcs)} functions)")


main()
